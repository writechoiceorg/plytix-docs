import { readFileSync } from 'node:fs';
import { createMDX } from 'fumadocs-mdx/next';
import { initOpenNextCloudflareForDev } from '@opennextjs/cloudflare';

initOpenNextCloudflareForDev();

const withMDX = createMDX();

const readJson = (file) => JSON.parse(readFileSync(new URL(file, import.meta.url), 'utf-8'));

// Moved pages: old /docs/reference/** URLs (long operationId slugs) to the short
// /reference/** ones, plus renamed guides.
// Exact page moves first, then prefix fallbacks; see redirects.json.
const movedPages = readJson('./redirects.json');

// V3 reference URLs that changed after launch, generated by `npm run api:build`
// whenever an operation's page URL changes (scripts/api/lib/redirects.mjs). Each
// also covers the `.md` variant that proxy.ts serves to LLM clients.
const v3Redirects = readJson('./redirects.v3.json');

/** @type {import('next').NextConfig} */
const config = {
  reactStrictMode: true,
  async redirects() {
    return [
      ...movedPages,
      ...v3Redirects.flatMap(({ source, destination }) => [
        { source, destination, permanent: true },
        { source: `${source}.md`, destination: `${destination}.md`, permanent: true },
      ]),
    ];
  },
};

export default withMDX(config);
