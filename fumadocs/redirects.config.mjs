// The redirect list served by next.config.mjs, built in one place so that
// scripts/check-redirects.mjs checks exactly what Next serves (NEW-011).

import { readFileSync } from 'node:fs';

const readJson = (file) => JSON.parse(readFileSync(new URL(file, import.meta.url), 'utf-8'));

const escapeRegex = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * @param {{ hiddenContent?: string[] }} [options] Content paths that aren't published
 *   (defaults to hidden-content.json). Pass `[]` for a full preview.
 */
export function buildRedirects({ hiddenContent = readJson('./hidden-content.json') } = {}) {
  // Moved pages: old /docs/reference/** URLs (long operationId slugs) to the short
  // /reference/** ones, plus renamed guides. Exact page moves first, then prefix
  // fallbacks; see redirects.json.
  const movedPages = readJson('./redirects.json');

  // V3 reference URLs that changed after launch, generated by `npm run api:build`
  // whenever an operation's page URL changes (scripts/api/lib/redirects.mjs). Each
  // also covers the `.md` variant that proxy.ts serves to LLM clients.
  const v3Redirects = readJson('./redirects.v3.json').flatMap(({ source, destination }) => [
    { source, destination, permanent: true },
    { source: `${source}.md`, destination: `${destination}.md`, permanent: true },
  ]);

  // Unpublished content (see hiddenContent in lib/shared.ts). For /reference/** and
  // /guides/** the URL path matches the content path, so a redirect whose
  // destination is under a hidden path is skipped: the old URL 404s instead of
  // redirecting to a page that isn't served.
  const isHidden = (destination) => {
    const path = destination.replace(/^\//, '').replace(/[#?].*$/, '').replace(/\.md$/, '');
    return hiddenContent.some((prefix) => path === prefix || path.startsWith(`${prefix}/`));
  };

  const all = [...movedPages, ...v3Redirects];
  const skipped = all.filter(({ source, destination }) => !source.includes(':') && isHidden(destination));

  // A prefix fallback (`/docs/reference/:path*` → `/reference/:path*`) would still
  // catch those old URLs and send them to a page that isn't served, so it skips
  // every hidden path below its destination and every skipped source below its own.
  const withoutHidden = (rule) => {
    const source = /^(.*)\/:path\*$/.exec(rule.source);
    const destination = /^(.*)\/:path\*$/.exec(rule.destination);
    if (!source || !destination) return [rule];
    const base = destination[1].replace(/^\//, '');
    // A hidden folder or page, and everything under it (`v3`, `v3/…`, `v3.md`).
    const hidden = hiddenContent
      .filter((prefix) => prefix.startsWith(`${base}/`))
      .map((prefix) => `${escapeRegex(prefix.slice(base.length + 1))}(?:[/.]|$)`);
    const coveredByHidden = (path) => hidden.some((pattern) => new RegExp(`^${pattern}`).test(path));
    // An old URL whose own redirect was skipped, unless a hidden prefix already covers it.
    const oldUrls = skipped
      .filter((r) => r.source.startsWith(`${source[1]}/`))
      .map((r) => r.source.slice(source[1].length + 1))
      .filter((path) => !coveredByHidden(path))
      .map((path) => `${escapeRegex(path)}$`);
    const excluded = [...hidden, ...oldUrls];
    if (excluded.length === 0) return [rule];
    return [
      { ...rule, source: source[1], destination: destination[1] },
      {
        ...rule,
        source: `${source[1]}/:path((?!(?:${excluded.join('|')})).+)`,
        destination: `${destination[1]}/:path`,
      },
    ];
  };

  return all.filter((r) => !skipped.includes(r)).flatMap(withoutHidden);
}
