import { llms, loader } from 'fumadocs-core/source';
import { fluentIconsPlugin } from './fluent-icons-plugin';
import { sidebarTitlePlugin } from './sidebar-title-plugin';
import { z } from 'zod';
import { absoluteUrl, appName, docsRoute, getPageUrl, isHiddenContent, siteDescription } from './shared';
import { defineDocs } from 'fumadocs-mdx/macro';
import { applyMdxPreset } from 'fumadocs-mdx/config';
import { metaSchema, pageSchema } from 'fumadocs-core/source/schema';
import { openapi } from './openapi';
import { renderOpenAPIPageMarkdown } from './openapi-markdown';
import { remarkStructureOptions } from './search-structure';
import { markdownExportOptions } from './markdown-export';

const docs = defineDocs({
  dir: 'content/docs',
  docs: {
    // `sidebarTitle`: optional shorter sidebar label (see lib/sidebar-title-plugin.ts).
    // `metaTitle` / `metaDescription`: optional <title> and meta description when the
    // page title alone is too generic for search results and shared links (STG-019, STG-020).
    schema: pageSchema.extend({
      sidebarTitle: z.string().optional(),
      metaTitle: z.string().optional(),
      metaDescription: z.string().optional(),
    }),
    // The preset keeps Fumadocs' default plugins; only the search index changes.
    mdxOptions: applyMdxPreset({ remarkStructureOptions }),
    postprocess: {
      // Components are exported as Markdown, not raw JSX (lib/markdown-export.ts, STG-012).
      includeProcessedMarkdown: markdownExportOptions,
    },
  },
  meta: {
    schema: metaSchema,
  },
});

// Unpublished content (see `hiddenContent` in lib/shared.ts) is dropped here, so
// nothing downstream (pages, sidebar, search, llms.txt, OG images) sees it.
const docsSource = docs.toFumadocsSource();
const publishedSource = {
  ...docsSource,
  files: docsSource.files.filter((file) => !isHiddenContent(file.path)),
};

// See https://fumadocs.dev/docs/headless/source-api for more info
export const source = loader({
  baseUrl: docsRoute,
  url: (slugs) => getPageUrl(slugs),
  source: publishedSource,
  plugins: [fluentIconsPlugin(), sidebarTitlePlugin(), openapi.loaderPlugin()],
});

type PageNode = Parameters<typeof source.getNodePage>[0];
type FolderNode = Parameters<typeof source.getNodeMeta>[0];
type TreeNode = { type?: string; name?: unknown; description?: unknown };

// The page tree root's `type` is optional; every other node has one.
const isRoot = (node: TreeNode) => !['page', 'folder', 'separator'].includes(node.type ?? 'root');

// Fumadocs' own llms.txt naming and descriptions, kept for every node but the root.
function defaultName(node: TreeNode): string {
  const own =
    node.type === 'page'
      ? source.getNodePage(node as PageNode)?.data.title
      : node.type === 'folder'
        ? source.getNodeMeta(node as FolderNode)?.data.title
        : undefined;
  return own ?? (typeof node.name === 'string' ? node.name : '');
}

function defaultDescription(node: TreeNode): string {
  const own =
    node.type === 'page'
      ? source.getNodePage(node as PageNode)?.data.description
      : node.type === 'folder'
        ? source.getNodeMeta(node as FolderNode)?.data.description
        : undefined;
  return own ?? (typeof node.description === 'string' ? node.description : '');
}

export const docsLlms = llms(source, {
  // The root of the page tree has no title or description of its own (STG-022).
  renderName: (node) => (isRoot(node) ? appName : defaultName(node)),
  renderDescription: (node) => (isRoot(node) ? siteDescription : defaultDescription(node)),
  renderPage: async (page) => {
    // Strip MDX comments (e.g. the "generated by Fumadocs" banner on endpoint pages).
    const processed = (await page.data.getText('processed')).replace(/\{\/\*[\s\S]*?\*\/\}/g, '');
    const body = [processed, renderOpenAPIPageMarkdown(page)]
      .filter((s) => s?.trim())
      .join('\n\n')
      // Site-relative links become absolute, so the export works outside the portal (STG-022).
      .replace(/\]\(\//g, `](${absoluteUrl('/')}`);

    return `# ${page.data.title} (${absoluteUrl(page.url)})

${body}`;
  },
});
