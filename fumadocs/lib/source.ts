import { llms, loader } from 'fumadocs-core/source';
import { fluentIconsPlugin } from './fluent-icons-plugin';
import { docsRoute, getPageUrl, isPublishedPath } from './shared';
import { defineDocs } from 'fumadocs-mdx/macro';
import { applyMdxPreset } from 'fumadocs-mdx/config';
import { metaSchema, pageSchema } from 'fumadocs-core/source/schema';
import { openapi } from './openapi';
import { renderOpenAPIPageMarkdown } from './openapi-markdown';
import { remarkStructureOptions } from './search-structure';

const docs = defineDocs({
  dir: 'content/docs',
  docs: {
    schema: pageSchema,
    // The preset keeps Fumadocs' default plugins; only the search index changes.
    mdxOptions: applyMdxPreset({ remarkStructureOptions }),
    postprocess: {
      includeProcessedMarkdown: true,
    },
  },
  meta: {
    schema: metaSchema,
  },
});

// Unpublished pages are dropped here, so every route, the search index and
// the MCP server (all built on `source`) treat them as nonexistent.
const docsSource = docs.toFumadocsSource();

// See https://fumadocs.dev/docs/headless/source-api for more info
export const source = loader({
  baseUrl: docsRoute,
  url: (slugs) => getPageUrl(slugs),
  source: { ...docsSource, files: docsSource.files.filter((file) => isPublishedPath(file.path)) },
  plugins: [fluentIconsPlugin(), openapi.loaderPlugin()],
});

export const docsLlms = llms(source, {
  renderPage: async (page) => {
    // Strip MDX comments (e.g. the "generated by Fumadocs" banner on endpoint pages).
    const processed = (await page.data.getText('processed')).replace(/\{\/\*[\s\S]*?\*\/\}/g, '');
    const body = [processed, renderOpenAPIPageMarkdown(page)]
      .filter((s) => s?.trim())
      .join('\n\n');

    return `# ${page.data.title} (${page.url})

${body}`;
  },
});
