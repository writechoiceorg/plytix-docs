// Custom Worker entry (wrangler `main`): password-protects the whole site, then
// hands the request to the Worker OpenNext generates.
//
// Set the password as the `DOCS_PASSWORD` secret in the Cloudflare dashboard;
// with no secret set, the site is public.
//
// - Browsers get a password-only login page. A correct password sets a signed
//   cookie for 30 days; changing the secret signs everyone out.
// - Scripts and MCP clients can send the password as HTTP Basic Auth instead
//   (any username), e.g. `curl -u x:<password>`.
// - `assets.run_worker_first` in wrangler.jsonc makes static files pass through
//   here too. See https://opennext.js.org/cloudflare/howtos/custom-worker

// @ts-ignore -- generated by `opennextjs-cloudflare build` (absent before the first build)
import { default as handler } from './.open-next/worker.js';

interface Env {
  DOCS_PASSWORD?: string;
}

// Workers-only API, missing from the DOM types this project compiles with.
type WorkersSubtleCrypto = SubtleCrypto & {
  timingSafeEqual(a: ArrayBuffer | ArrayBufferView, b: ArrayBuffer | ArrayBufferView): boolean;
};

const COOKIE = 'docs_auth';
const SESSION_SECONDS = 30 * 24 * 60 * 60;
const LOGIN_PATH = '/__auth/login';
const LOGOUT_PATH = '/__auth/logout';

const encoder = new TextEncoder();

// Compares SHA-256 hashes so the check takes the same time whatever was typed.
async function matches(given: string, expected: string): Promise<boolean> {
  const [a, b] = await Promise.all([
    crypto.subtle.digest('SHA-256', encoder.encode(given)),
    crypto.subtle.digest('SHA-256', encoder.encode(expected)),
  ]);
  return (crypto.subtle as WorkersSubtleCrypto).timingSafeEqual(a, b);
}

// Session token: "<expiry>.<HMAC of the expiry, keyed by the password>".
async function sign(password: string, expires: number): Promise<string> {
  const key = await crypto.subtle.importKey('raw', encoder.encode(password), { name: 'HMAC', hash: 'SHA-256' }, false, [
    'sign',
  ]);
  const mac = await crypto.subtle.sign('HMAC', key, encoder.encode(`docs-auth:${expires}`));
  const hex = [...new Uint8Array(mac)].map((b) => b.toString(16).padStart(2, '0')).join('');
  return `${expires}.${hex}`;
}

async function hasValidSession(request: Request, password: string): Promise<boolean> {
  const token = (request.headers.get('Cookie') ?? '')
    .split(/;\s*/)
    .find((c) => c.startsWith(`${COOKIE}=`))
    ?.slice(COOKIE.length + 1);
  const expires = Number(token?.split('.')[0]);
  if (!token || !Number.isFinite(expires) || expires < Date.now() / 1000) return false;
  return matches(token, await sign(password, expires));
}

function basicAuthPassword(request: Request): string | undefined {
  const [scheme, encoded] = (request.headers.get('Authorization') ?? '').split(' ');
  if (scheme !== 'Basic' || !encoded) return;
  try {
    // "username:password"; the password itself may contain colons.
    return atob(encoded).split(':').slice(1).join(':');
  } catch {
    return;
  }
}

// Only same-site paths, never back to the auth routes.
function safeNext(value: unknown): string {
  if (typeof value !== 'string' || !value.startsWith('/') || value.startsWith('//') || value.startsWith('/\\')) return '/';
  return value.startsWith('/__auth/') ? '/' : value;
}

const escapeHtml = (s: string) =>
  s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);

