function redirect(location: string, cookie?: string): Response {
  const headers = new Headers({ Location: location, 'Cache-Control': 'no-store' });
  if (cookie) headers.set('Set-Cookie', cookie);
  return new Response(null, { status: 303, headers });
}

async function login(request: Request, password: string): Promise<Response> {
  const form = await request.formData().catch(() => undefined);
  const given = form?.get('password');
  const next = safeNext(form?.get('next'));
  if (typeof given !== 'string' || !(await matches(given, password))) return loginPage(next, true);

  const expires = Math.floor(Date.now() / 1000) + SESSION_SECONDS;
  const token = await sign(password, expires);
  return redirect(next, `${COOKIE}=${token}; Path=/; Max-Age=${SESSION_SECONDS}; HttpOnly; Secure; SameSite=Lax`);
}

export default {
  async fetch(request: Request, env: Env, ctx: unknown): Promise<Response> {
    const password = env.DOCS_PASSWORD;
    if (!password) return handler.fetch(request, env, ctx);

    const url = new URL(request.url);
    if (url.pathname === LOGIN_PATH && request.method === 'POST') return login(request, password);
    if (url.pathname === LOGOUT_PATH) return redirect('/', `${COOKIE}=; Path=/; Max-Age=0; HttpOnly; Secure; SameSite=Lax`);

    const basic = basicAuthPassword(request);
    if ((await hasValidSession(request, password)) || (basic !== undefined && (await matches(basic, password)))) {
      return handler.fetch(request, env, ctx);
    }

    // Page navigations get the login form; everything else a plain 401.
    if (request.method === 'GET' && request.headers.get('Accept')?.includes('text/html')) {
      return loginPage(safeNext(url.pathname + url.search), false);
    }
    return new Response('Authentication required', {
      status: 401,
      headers: { 'Content-Type': 'text/plain; charset=utf-8', 'Cache-Control': 'no-store' },
    });
  },
};
