// Coverage: how much of the public spec our overlays have enriched. Reported
// on every build; with --strict-coverage, gaps become blocking (turned on once
// every tag has been through the content workflow).

import { operations } from './util.mjs';

// FastAPI defaults we always want replaced.
const FASTAPI_SUMMARY = /^[A-Z][A-Za-z]*(?:-[A-Z][A-Za-z]*)+(?: [A-Z][a-z]+)*$/; // "Search-Products", "Get-Products Subpath"
const FASTAPI_OPERATION_ID = /_api_v3_|_(?:get|put|post|patch|delete)$/;

const hasExample = (media) =>
  Object.values(media ?? {}).some((m) => m?.examples || m?.example !== undefined);

export function computeCoverage(spec, records) {
  const edited = new Set();
  for (const r of records) {
    if (r.shape !== 'operation' || !r.file.startsWith('ops/') || r.matches.length === 0) continue;
    const m = r.target.match(/^\$\.paths\['([^']+)'\]\.(\w+)$/);
    if (m) edited.add(`${m[2].toUpperCase()} ${m[1]}`);
  }

  const rows = [];
  for (const { key, op } of operations(spec)) {
    const params = op.parameters ?? [];
    const responses = Object.entries(op.responses ?? {});
    rows.push({
      key,
      tag: op.tags?.[0] ?? '(none)',
      edited: edited.has(key),
      cleanSummary: !!op.summary && !FASTAPI_SUMMARY.test(op.summary),
      description: !!op.description?.trim(),
      cleanOperationId: !!op.operationId && !FASTAPI_OPERATION_ID.test(op.operationId),
      paramsTotal: params.length,
      paramsDescribed: params.filter((p) => p.description?.trim()).length,
      responsesTotal: responses.filter(([, r]) => r.content).length,
      responsesWithExamples: responses.filter(([, r]) => r.content && hasExample(r.content)).length,
      requestBody: !!op.requestBody,
      requestBodyExample: !!op.requestBody && hasExample(op.requestBody.content),
    });
  }

  const count = (f) => rows.filter(f).length;
  const sum = (f) => rows.reduce((n, r) => n + f(r), 0);
  const totals = {
    operations: rows.length,
    edited: count((r) => r.edited),
    cleanSummary: count((r) => r.cleanSummary),
    description: count((r) => r.description),
    cleanOperationId: count((r) => r.cleanOperationId),
    paramsTotal: sum((r) => r.paramsTotal),
    paramsDescribed: sum((r) => r.paramsDescribed),
    responsesTotal: sum((r) => r.responsesTotal),
    responsesWithExamples: sum((r) => r.responsesWithExamples),
    requestBodies: count((r) => r.requestBody),
    requestBodyExamples: count((r) => r.requestBodyExample),
  };

  const strictErrors = rows
    .filter((r) => !r.edited || !r.cleanOperationId)
    .map((r) => `${r.key}: ${!r.edited ? 'no overlay edits yet' : 'still has the FastAPI operationId'}`);

  return { rows, totals, strictErrors };
}

export function renderCoverage({ rows, totals }) {
  const pct = (a, b) => (b ? `${Math.round((100 * a) / b)}%` : 'n/a');
  const yes = (b) => (b ? 'yes' : '**no**');
  const lines = [
    '# V3 overlay coverage',
    '',
    'Generated by `npm run api:build`. Public operations only (after the visibility filter).',
    '',
    '| Metric | Covered | Total | % |',
    '|---|---|---|---|',
    `| Operations with overlay edits (\`ops/*.yaml\`) | ${totals.edited} | ${totals.operations} | ${pct(totals.edited, totals.operations)} |`,
    `| Hand-written summary (page title) | ${totals.cleanSummary} | ${totals.operations} | ${pct(totals.cleanSummary, totals.operations)} |`,
    `| Operation description | ${totals.description} | ${totals.operations} | ${pct(totals.description, totals.operations)} |`,
    `| Clean operationId (page URL) | ${totals.cleanOperationId} | ${totals.operations} | ${pct(totals.cleanOperationId, totals.operations)} |`,
    `| Parameters with a description | ${totals.paramsDescribed} | ${totals.paramsTotal} | ${pct(totals.paramsDescribed, totals.paramsTotal)} |`,
    `| Responses (with a body) that have examples | ${totals.responsesWithExamples} | ${totals.responsesTotal} | ${pct(totals.responsesWithExamples, totals.responsesTotal)} |`,
    `| Request bodies with examples | ${totals.requestBodyExamples} | ${totals.requestBodies} | ${pct(totals.requestBodyExamples, totals.requestBodies)} |`,
    '',
    '## Per operation',
    '',
    '| Operation | Tag | Edited | Summary | Description | operationId | Params described | Response examples | Body example |',
    '|---|---|---|---|---|---|---|---|---|',
  ];
  for (const r of [...rows].sort((a, b) => a.tag.localeCompare(b.tag) || a.key.localeCompare(b.key))) {
    lines.push(
      `| \`${r.key}\` | ${r.tag} | ${yes(r.edited)} | ${yes(r.cleanSummary)} | ${yes(r.description)} | ${yes(r.cleanOperationId)} | ${r.paramsDescribed}/${r.paramsTotal} | ${r.responsesWithExamples}/${r.responsesTotal} | ${r.requestBody ? yes(r.requestBodyExample) : 'n/a'} |`,
    );
  }
  return lines.join('\n') + '\n';
}
